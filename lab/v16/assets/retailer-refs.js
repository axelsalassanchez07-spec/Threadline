const CATEGORY_TYPE={Tops:'top',Outerwear:'outer',Bottoms:'bottom',Shoes:'shoe',Accessories:'accessory'};
export function matchesForGarment(item){
 const type=CATEGORY_TYPE[item.category];if(!type)return [];
 const kind=String(item.kind||'').toLowerCase();
 const tokens=kind.split(/\s+/).filter(x=>x.length>=4);
 return RETAILER_REFERENCES.filter(p=>p.type===type).map(p=>{
  const pt=String(p.kind||'').toLowerCase();
  const overlap=tokens.some(t=>pt.includes(t)||t.includes(pt));
  const kindMatch=pt===kind;
  const colorMatch=p.color===item.color;
  return{...p,score:(kindMatch?10:0)+(overlap?5:0)+(colorMatch?1:0),reasonable:kindMatch||overlap};
 }).filter(p=>p.reasonable).sort((a,b)=>b.score-a.score).slice(0,2);
}
